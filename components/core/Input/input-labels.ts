export function useCoreInputLabels() {
  const { locale } = useLocale();
  const exact = Object.keys(labels).find((key) => key.toLowerCase() === locale.toLowerCase());
  const language = locale.split('-')[0];
  const matched = exact ?? Object.keys(labels).find((key) => key === language) ?? 'en';
  return labels[matched as keyof typeof labels];
}
