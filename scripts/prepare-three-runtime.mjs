import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Bind Geul's bundled libraries to the exact installed Three.js runtime on jsDelivr. */
export async function prepareThreeRuntime() {
  const versions = {};
  for (const name of ['three', 'three-stdlib', '@echovisionlab/ionian', 'mitt']) {
    const pkg = JSON.parse(await readFile(resolve(root, 'node_modules', name, 'package.json'), 'utf8'));
    if (!/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/u.test(pkg.version)) {
      throw new Error(`Expected an exact installed version for ${name}`);
    }
    versions[name] = pkg.version;
  }
  const manifest = {
    versions,
    threeUrl: `https://cdn.jsdelivr.net/npm/three@${versions.three}/build/three.module.min.js`,
  };
  const output = resolve(root, 'lib/three/cdn-runtime-manifest.json');
  const source = `${JSON.stringify(manifest, null, 2)}\n`;
  const previous = await readFile(output, 'utf8').catch(() => '');
  if (previous !== source) await writeFile(output, source);
  // The app owns this alias. Ionian itself keeps standard, CDN-independent imports.
  // Generate every installed runtime export so transitive loaders use identical classes.
  const three = await import(pathToFileURL(resolve(root, 'node_modules/three/build/three.module.js')).href);
  const names = Object.keys(three).sort();
  if (names.some((name) => !/^[A-Za-z_$][\w$]*$/u.test(name))) {
    throw new Error('Unsupported Three.js runtime export');
  }
  const shim = [
    '// Generated by scripts/prepare-three-runtime.mjs. Do not edit.',
    "import { loadThreeRuntime } from './cdn-runtime';",
    'const THREE = await loadThreeRuntime();',
    ...names.map((name) => `export const ${name} = THREE.${name};`),
    '',
  ].join('\n');
  const shimPath = resolve(root, 'lib/three/three-cdn-module.generated.mjs');
  const previousShim = await readFile(shimPath, 'utf8').catch(() => '');
  if (previousShim !== shim) await writeFile(shimPath, shim);
  return manifest;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await prepareThreeRuntime();
}
