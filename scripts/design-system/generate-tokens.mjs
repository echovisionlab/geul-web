import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import {
  primitiveTokens,
  semanticThemes,
  invariantTokens,
  authoredEditorPalettes,
  derivedTokenRoles,
  responsiveTokens,
  printTokens,
} from '../../components/core/design-tokens.ts';
import prettier from 'prettier';

const target = new URL('../../lib/styles/design-tokens.css', import.meta.url);
const breakpointTarget = new URL('../../lib/styles/design-breakpoints.json', import.meta.url);
const shared = { ...invariantTokens };
for (const [category, values] of Object.entries(primitiveTokens)) {
  // Palette materials are projected through semantic roles. Media queries cannot consume custom
  // properties, so breakpoints are projected only to design-breakpoints.json (PostCSS) and JS.
  if (category === 'colors' || category === 'breakpoints') continue;
  const prefix = category.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);
  for (const [name, value] of Object.entries(values)) shared[`${prefix}-${name}`] = value;
}
shared['brand-default'] = primitiveTokens.colors.brand;
for (const [role, scale] of Object.entries(derivedTokenRoles)) {
  if (
    !Object.hasOwn(shared, role) ||
    !Object.hasOwn(shared, scale) ||
    Object.hasOwn(derivedTokenRoles, scale) ||
    shared[role] !== shared[scale]
  ) {
    throw new Error(`Derived token ${role} must follow ${scale} in both TypeScript and CSS.`);
  }
  shared[role] = `var(--geul-${scale})`;
}
const declarations = (tokens, prefix = 'geul') =>
  Object.entries(tokens)
    .map(
      ([key, value]) => `  --${prefix}-${key}: ${value.replace(/#([\da-f])\1([\da-f])\2([\da-f])\3\b/gi, '#$1$2$3')};`,
    )
    .join('\n');
if (Object.keys(semanticThemes.light).sort().join() !== Object.keys(semanticThemes.dark).sort().join()) {
  throw new Error('Light and dark themes must define exactly the same roles.');
}
if (
  Object.keys(authoredEditorPalettes.light).sort().join() !== Object.keys(authoredEditorPalettes.dark).sort().join()
) {
  throw new Error('Light and dark authored palettes must define exactly the same durable names.');
}
const themeDeclarations = (mode) =>
  `${declarations(semanticThemes[mode])}\n${declarations(authoredEditorPalettes[mode], 'editor')}`;
// Paper is always printed with the light semantic roles. Explicit dark themes and custom presets
// (inline root properties) project screen values; print overrides them with the light authority.
const printThemeCss = `@media print {\n :root,\n [data-geul-theme] {\n${themeDeclarations('light').replace(/;$/gmu, ' !important;')}\n }\n}\n`;
const knownRole = (role, source) => {
  if (!Object.hasOwn(shared, role)) throw new Error(`${source} ${role} must replace an existing role.`);
  if (Object.hasOwn(derivedTokenRoles, role)) throw new Error(`${source} ${role} is derived; project its scale.`);
};
const responsiveCss = Object.entries(responsiveTokens)
  .map(([breakpoint, tokens]) => {
    if (!Object.hasOwn(primitiveTokens.breakpoints, breakpoint))
      throw new Error(`Responsive tokens use unknown breakpoint ${breakpoint}.`);
    Object.keys(tokens).forEach((role) => knownRole(role, 'Responsive token'));
    return `@media (min-width: ${primitiveTokens.breakpoints[breakpoint]}) {\n :root {\n${declarations(tokens)}\n }\n}\n`;
  })
  .join('\n');
Object.keys(printTokens).forEach((role) => knownRole(role, 'Print token'));
// Paper type follows every responsive block: printed pages are wider than `sm`, so a min-width
// projection would otherwise replace the paper scale.
const printTypographyCss = `@media print {\n :root {\n${declarations(printTokens)}\n }\n}\n`;
const inputCapabilityCss = `@media (any-pointer: coarse) {\n :root {\n --geul-interaction-minimum: var(--geul-interaction-touch);\n }\n}\n`;
const output = await prettier.format(
  `/* Generated by scripts/design-system/generate-tokens.mjs. Edit components/core/design-tokens.ts. */\n:root {\n${declarations(shared)}\n${themeDeclarations('light')}\n}\n\n${inputCapabilityCss}\n@media (prefers-color-scheme: dark) {\n html:not([data-geul-theme='light']) {\n${themeDeclarations('dark')}\n }\n}\n\n[data-geul-theme='light'] {\n${themeDeclarations('light')}\n}\n\n[data-geul-theme='dark'] {\n${themeDeclarations('dark')}\n}\n\n${printThemeCss}\n${responsiveCss}\n${printTypographyCss}`,
  { ...(await prettier.resolveConfig(fileURLToPath(target))), parser: 'css' },
);
// Media queries cannot consume CSS custom properties. PostCSS uses this generated projection.
const breakpointOutput =
  JSON.stringify(
    Object.fromEntries(
      Object.entries(primitiveTokens.breakpoints).map(([key, value]) => [`mantine-breakpoint-${key}`, value]),
    ),
    null,
    2,
  ) + '\n';
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8').catch(() => '')) !== output) {
    console.error('Generated design tokens are stale. Run node scripts/design-system/generate-tokens.mjs.');
    process.exitCode = 1;
  } else console.log('Generated design tokens are current.');
  if ((await readFile(breakpointTarget, 'utf8').catch(() => '')) !== breakpointOutput) {
    console.error('Generated breakpoint projection is stale. Run node scripts/design-system/generate-tokens.mjs.');
    process.exitCode = 1;
  }
} else {
  await writeFile(target, output);
  await writeFile(breakpointTarget, breakpointOutput);
  console.log('Generated lib/styles/design-tokens.css.');
}
