/** Import census, explicitly not a rendering or all-state coverage claim. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import ts from '@typescript/tooling';
import prettier from 'prettier';
const root = path.resolve(import.meta.dirname, '../..');
const inventory = JSON.parse(readFileSync(path.join(root, 'docs/design-system/ui-inventory.json'), 'utf8'));
const files = new Set(inventory.sourceFiles);
function resolve(file, name) {
  const base = name.startsWith('@/')
    ? name.slice(2)
    : name.startsWith('.')
      ? path.posix.normalize(path.posix.join(path.posix.dirname(file), name))
      : null;
  return (
    base &&
    [base, ...['.tsx', '.ts', '/index.tsx', '/index.ts'].map((suffix) => base + suffix)].find((candidate) =>
      files.has(candidate),
    )
  );
}
const graph = new Map();
function dependencies(file) {
  if (graph.has(file)) return graph.get(file);
  const source = ts.createSourceFile(file, readFileSync(path.join(root, file), 'utf8'), ts.ScriptTarget.Latest, true);
  const result = new Set();
  for (const node of source.statements) {
    if (
      !(ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) ||
      !node.moduleSpecifier ||
      !ts.isStringLiteral(node.moduleSpecifier) ||
      node.isTypeOnly ||
      node.importClause?.isTypeOnly
    )
      continue;
    if (
      ts.isImportDeclaration(node) &&
      node.importClause?.namedBindings &&
      ts.isNamedImports(node.importClause.namedBindings) &&
      !node.importClause.name &&
      node.importClause.namedBindings.elements.every((item) => item.isTypeOnly)
    )
      continue;
    if (
      ts.isExportDeclaration(node) &&
      node.exportClause &&
      ts.isNamedExports(node.exportClause) &&
      node.exportClause.elements.every((item) => item.isTypeOnly)
    )
      continue;
    const target = resolve(file, node.moduleSpecifier.text);
    if (target) result.add(target);
  }
  function visit(node) {
    if (
      ts.isCallExpression(node) &&
      node.expression.kind === ts.SyntaxKind.ImportKeyword &&
      ts.isStringLiteral(node.arguments[0])
    ) {
      const target = resolve(file, node.arguments[0].text);
      if (target) result.add(target);
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  graph.set(file, [...result]);
  return graph.get(file);
}
function closure(file) {
  const seen = new Set();
  const queue = [file];
  while (queue.length) {
    const current = queue.shift();
    if (seen.has(current)) continue;
    seen.add(current);
    queue.push(...dependencies(current).filter((target) => /^(stories|features|app)\//.test(target)));
  }
  return seen;
}
const stories = inventory.stories.map((story) => ({ ...story, related: closure(story.file) }));
const domains = inventory.domains.map((domain) => {
  const candidates = inventory.components.filter((component) => domain.components.includes(component.file));
  const components = candidates.map((component) => ({
    file: component.file,
    hasJsx: component.composedJsx.length > 0,
    directStories: stories
      .filter((story) => dependencies(story.file).includes(component.file))
      .map((story) => story.title),
    relatedStories: stories.filter((story) => story.related.has(component.file)).map((story) => story.title),
  }));
  return {
    domain: domain.domain,
    category: domain.category,
    components,
    jsxWithoutStoryRelationship: components.filter((c) => c.hasJsx && !c.relatedStories.length).map((c) => c.file),
  };
});
const output = {
  schemaVersion: 1,
  sourceManifestHash: inventory.manifestHash,
  methodology:
    'All inventoried Feature component candidates. Direct value imports, literal lazy imports and transitive source relationships through production owners/local adapters are indexed separately. A dependency can be unused or render conditionally; neither relationship proves rendered states, route parity or design compliance. Empty JSX records include runtime/lazy/controller boundaries and must be inspected before treating them as visual gaps.',
  counts: {
    domains: domains.length,
    componentFiles: domains.reduce((sum, d) => sum + d.components.length, 0),
    jsxWithoutStoryRelationship: domains.reduce((sum, d) => sum + d.jsxWithoutStoryRelationship.length, 0),
  },
  domains,
};
let md = `# Feature preview source relationships\n\nGenerated by \`node scripts/design-system/feature-preview-index.mjs\`; \`--check\` detects drift. [Complete JSON](./feature-preview-index.json).\n\n${output.methodology}\n\n| Feature domain | Source candidates | JSX without any story relationship |\n| --- | ---: | ---: |\n${domains.map((d) => `| [${d.domain}](../../features/${d.domain}) | ${d.components.length} | ${d.jsxWithoutStoryRelationship.length} |`).join('\n')}\n\n## Every candidate\n\nDirect and transitive imports are source evidence, not visual approval. No component is marked design-compliant by this index.\n\n`;
for (const d of domains) {
  md += `### ${d.domain}\n\n| Production candidate | Direct story imports | Transitive story relationships |\n| --- | --- | --- |\n${d.components.map((c) => `| [${path.basename(c.file)}](../../${c.file}) | ${c.directStories.join('<br/>') || 'None'} | ${c.relatedStories.join('<br/>') || (c.hasJsx ? '**Missing relationship**' : 'Runtime/lazy/indirect candidate; inspect source')} |`).join('\n')}\n\n`;
}
for (const [file, value, parser] of [
  ['docs/design-system/feature-preview-index.json', JSON.stringify(output), 'json'],
  ['docs/design-system/feature-preview-index.md', md, 'markdown'],
]) {
  const formatted = await prettier.format(value, {
    ...(await prettier.resolveConfig(path.join(root, '.prettierrc.json'))),
    parser,
  });
  const target = path.join(root, file);
  if (process.argv.includes('--check')) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== formatted) {
      console.error(`Stale ${file}`);
      process.exitCode = 1;
    }
  } else writeFileSync(target, formatted);
}
console.log(JSON.stringify(output.counts));
